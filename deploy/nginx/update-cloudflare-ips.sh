#!/usr/bin/env bash
# Regenerates /etc/nginx/snippets/cloudflare-real-ip.conf from Cloudflare's published ranges and
# reloads nginx. Run as root on the VPS. Cloudflare changes these rarely (announced in advance);
# re-run after an announcement, or from a monthly cron:
#   0 4 1 * *  /opt/oxygenquiz/deploy/nginx/update-cloudflare-ips.sh >> /var/log/cf-ips.log 2>&1
#
# Refuses to write an empty or partial list: an empty file would make nginx trust no proxy, so every
# visitor would appear as a Cloudflare edge address and share one rate-limit bucket.
set -euo pipefail

TARGET=/etc/nginx/snippets/cloudflare-real-ip.conf
TMP=$(mktemp)

v4=$(curl -fsS https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS https://www.cloudflare.com/ips-v6)

count=$(printf '%s\n%s\n' "$v4" "$v6" | grep -c '/')
if [ "$count" -lt 10 ]; then
  echo "Only $count ranges fetched — refusing to replace $TARGET" >&2
  exit 1
fi

{
  echo "# Generated by update-cloudflare-ips.sh on $(date -u +%Y-%m-%d). Do not edit by hand."
  echo "# See deploy/nginx/cloudflare-real-ip.conf in the repo for what this does."
  for ip in $v4 $v6; do echo "set_real_ip_from $ip;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

install -m 644 "$TMP" "$TARGET"
rm -f "$TMP"
nginx -t
systemctl reload nginx
echo "Updated $TARGET with $count ranges."
